let current = DEFAULT_LOCALE;

/** 目前語系。 */
export function locale() {
  return current;
}

/**
 * 切換語系。回傳實際生效的語系：不在 LOCALES 內的一律退回預設語系，
 * 因為拼錯的語系代碼若靜默生效，只會讓畫面變成半中半英。
 */
export function setLocale(next) {
  current = LOCALES.includes(next) ? next : DEFAULT_LOCALE;
  return current;
}

function interpolate(template, params) {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : whole,
  );
}

/**
 * 取字串。查不到 key 時回傳 key 本身並留下前導 ‼——
 * 寧可在畫面上看到一個奇怪符號，也不要靜默顯示空白讓人以為功能壞了。
 */
export function t(key, params) {
  const dict = CATALOGS[current] ?? CATALOGS[DEFAULT_LOCALE];
  const value = dict[key] ?? CATALOGS[DEFAULT_LOCALE][key];
  if (value === undefined) {
    if (typeof console !== 'undefined') console.warn(`[i18n] missing key: ${key}`);
    return `‼${key}`;
  }
  return interpolate(value, params);
}

/** 所有語系的 key 集合（測試用來檢查齊備度）。 */
export function catalogKeys() {
  return Object.fromEntries(Object.entries(CATALOGS).map(([locale, dict]) => [locale, Object.keys(dict)]));
}

export const catalogs = CATALOGS;

/**
 * 把 index.html 靜態標記換成目前語系。
 * data-i18n       → textContent
 * data-i18n-attr  → "placeholder:key,title:key" 形式，避免為了翻譯而改變 DOM 結構。
 */
export function applyDom(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) {
    el.textContent = t(el.dataset.i18n);
  }

  for (const el of root.querySelectorAll('[data-i18n-attr]')) {
    for (const pair of el.dataset.i18nAttr.split(',')) {
      const [attr, key] = pair.split(':').map((s) => s.trim());
      if (attr && key) el.setAttribute(attr, t(key));
    }
  }

  if (root.documentElement) {
    root.documentElement.lang = current;
  }
}